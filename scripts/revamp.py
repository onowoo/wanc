OUTDOOR = ["村口", "巷口", "广场", "山道", "街道", "长街", "集市", "路口", "门外", "院外",
           "野外", "山路", "桥头", "井边", "田埂", "田间"]
INDOOR = ["茶馆", "店内", "店中", "馆", "铺", "堂", "屋", "宅", "府", "楼", "间", "房", "室内"]


def fix_scene_text(src: str) -> str:
    pat = re.compile(r"【内｜([^｜】]+)｜([日夜晚])】")

    def rep(m):
        loc = m.group(1)
        if any(k in loc for k in OUTDOOR) and not any(i in loc for i in INDOOR):
            return f"【外｜{loc}｜{m.group(2)}】"
        return m.group(0)

    return pat.sub(rep, src)


